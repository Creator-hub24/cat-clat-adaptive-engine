def import_paths(family: str) -> list[Path]:
    """Imported banks one app serves: the AptiSetu banks plus that family's own Claude-curated bank only."""
    return IMPORT_PATHS + ([claude_bank_path(family)] if family in CLAUDE_FAMILIES else [])
REVIEW_STATUSES = ("unreviewed", "approved", "rejected")
NEAR_DUP_JACCARD = 0.6


# ---------------------------------------------------------------- io
def load_json_bank(path: Path) -> dict:
    if not Path(path).exists():
        return {"meta": {"version": 1}, "questions": []}
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def save_json_bank(data: dict, path: Path) -> None:
    """Atomic write so an interrupted build never corrupts the bank."""
    path = Path(path)
    data.setdefault("meta", {})["updated_at"] = dt.datetime.now(dt.timezone.utc).isoformat()
    tmp = path.with_suffix(".json.tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    os.replace(tmp, path)


# ---------------------------------------------------------------- dedupe
def normalize(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", str(text).lower()).strip()


def text_hash(q: dict) -> str:
    opts = " ".join(normalize(v) for _, v in sorted(q.get("options", {}).items()))
    return hashlib.sha256((normalize(q["question_text"]) + "|" + opts).encode()).hexdigest()


def shingles(text: str, n: int = 5) -> set:
    w = normalize(text).split()
    return {" ".join(w[i:i + n]) for i in range(max(1, len(w) - n + 1))}


def jaccard(a: set, b: set) -> float:
    return len(a & b) / len(a | b) if a and b else 0.0


def is_duplicate(q: dict, existing: list[dict], threshold: float = NEAR_DUP_JACCARD) -> str | None:
    """Return a reason string if q duplicates (exactly or nearly) anything in existing."""
    h = text_hash(q)
    sh = shingles(q["question_text"])
    for e in existing:
        if e.get("text_hash", text_hash(e)) == h:
            return f"exact duplicate of {e.get('id')}"
        if e.get("topic") == q.get("topic") and jaccard(sh, shingles(e["question_text"])) >= threshold:
            return f"near-duplicate of {e.get('id')}"
    return None


# ---------------------------------------------------------------- serving
def servable(questions: list[dict]) -> list[dict]:
    return [q for q in questions if q.get("review_status", "approved") != "rejected" and q.get("verified", True)]


SCHEDULED_AI_SOURCE = "AI bank"  # pre-generated by scripts/build_bank.py / the daily routine


def serving_pool(seed: list[dict], ai: list[dict], imported: list[dict] | None = None) -> list[dict]:
    """Seed + scheduled AI bank (rejected excluded) + imports (excluded items left out). Scheduled AI items carry scheduled_ai=True
    so pick_unseen serves them first."""
    out = []
    for q in seed:
        q = dict(q, source="Seed bank", verified=True,
                 verification=["hand-checked"] + (["computed"] if q.get("verify_code") else []))
        out.append(q)
    for q in servable(ai):
        out.append(dict(q, scheduled_ai=True,
                        source=SCHEDULED_AI_SOURCE + (" (faculty-approved)" if q.get("review_status") == "approved"
                                                      else " (faculty review pending)")))
    for q in servable_imports(imported or []):
        # verified/verification come from the import (data/aptisetu_curation/verified_ids.json); items that were
        # not independently checked keep verified=False and show as unverified
        # Claude-curated items name their bank in import_source (data/claude_curation, every item verified)
        out.append(dict(q, source=q.get("import_source") or APTISETU_SOURCE, verified=bool(q.get("verified")),
                        verification=list(q.get("verification") or [])))
    return out


def servable_imports(questions: list[dict]) -> list[dict]:
    """Imported items minus those on the exclusion list (kept in the bank with an 'excluded' record)."""
    return [q for q in questions if not q.get("excluded")]


def pick_unseen(pool: list[dict], topic: str, difficulty: str, seen: set, rng) -> dict | None:
    """Unseen question for this topic+level; None if the user has exhausted that cell.
    Scheduled (pre-generated) AI questions come first, freshest generation day first, so today's new
    questions are served before older ones; the rest of the bank (seed, family sample bank, AptiSetu and
    Claude-curated imports) is used only once this user has seen every scheduled one in the cell."""
    fresh = [q for q in pool if q["topic"] == topic and q["difficulty"] == difficulty and q["id"] not in seen]
    scheduled = [q for q in fresh if q.get("scheduled_ai")]
    if scheduled:  # freshest batch first: the most recent generation day among unseen scheduled items
        newest = max(batch_day(q) for q in scheduled)
        return dict(rng.choice([q for q in scheduled if batch_day(q) == newest]))
    return dict(rng.choice(fresh)) if fresh else None


def batch_day(q: dict) -> str:
    """Generation day (YYYY-MM-DD, from created_at) of a scheduled AI item; '' if unknown (treated as oldest)."""
    return str(q.get("created_at") or "")[:10]
